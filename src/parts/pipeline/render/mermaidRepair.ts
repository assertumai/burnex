/**
 * Починка частой ошибки агентов в Mermaid (`render-design`): подпись узла,
 * начатая с `/` или `\` без кавычек — `A[/burnex/schema/*.json]`. Mermaid
 * читает `[/` и `[\` как начало трапеции или параллелограмма и ждёт закрытия
 * `/]` или `\]`; без него разбор падает, и диаграмма не рисуется.
 *
 * Функция берёт такие подписи в кавычки, оставляя настоящие фигуры
 * (`[/текст/]`, `[\текст\]`, `[/текст\]`, `[\текст/]`) как есть. Её зовут
 * только после отказа разбора: корректная диаграмма не меняется. Функция
 * самодостаточна — офлайн-HTML встраивает её текстом (`toString()`), поэтому
 * внешних имён внутри нет.
 */
export function repairMermaidLabels(source: string): string {
  return source.replace(/(\b[A-Za-z0-9_-]+)\[([/\\][^\]\n]*)\]/g, (whole: string, id: string, label: string) => {
    const last = label.charAt(label.length - 1);
    if (label.length > 1 && (last === '/' || last === '\\')) return whole;
    return `${id}["${label.replace(/"/g, '#quot;')}"]`;
  });
}
