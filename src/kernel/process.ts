import { uptime } from 'node:os';

/**
 * Момент последней загрузки машины. `os.uptime()` округлён до секунд, поэтому
 * граница берётся с запасом в минуту: ошибиться в сторону «процесс жив»
 * безопаснее (планировщик пропустит момент, lock подождёт), чем в сторону
 * «мёртв» (два прогона одного пайплайна или два писателя очереди разом).
 */
function bootTimeMs(now: number): number {
  return now - uptime() * 1000 - 60_000;
}

/**
 * Жив ли процесс. Сигнал 0 ничего не посылает, а только сообщает, есть ли
 * такой процесс и доступен ли он: `ESRCH` — нет такого процесса, `EPERM` —
 * процесс есть, но принадлежит другому пользователю, то есть жив.
 *
 * `since` — момент (мс от эпохи), с которого процесс заведомо должен
 * существовать. Если он раньше загрузки машины, идентификатор после
 * перезагрузки мог достаться постороннему процессу, и сигнал 0 соврал бы:
 * такой процесс считается мёртвым, не дожидаясь сигнала. Нечисловой `since`
 * (не разобранная дата) проверку загрузки пропускает.
 */
export function isProcessAlive(pid: number, since?: number, now: number = Date.now()): boolean {
  if (since !== undefined && !Number.isNaN(since) && since < bootTimeMs(now)) return false;
  try {
    process.kill(pid, 0);
    return true;
  } catch (error) {
    return (error as NodeJS.ErrnoException).code === 'EPERM';
  }
}
